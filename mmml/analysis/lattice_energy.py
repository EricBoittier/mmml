"""Lattice energy and sublimation enthalpy of a molecular crystal under CGenFF.

This deliberately does not go through ``mmml md-system --evaluate-npz``. That
path resolves a periodic cell to a single cubic side
(:func:`mmml.cli.run.md_stage_summary.cubic_box_side_from_cell`), which is fine
for the liquid boxes it was written for and wrong for a crystal: the acetone
Pbca cell (9.17 x 7.53 x 21.25 A) would be run as a 12.65 A cube. Everything
here therefore carries the full ``(3, 3)`` cell.

The energy is an *explicit lattice sum*, not a minimum-image sum. The minimum
image convention caps the cutoff at half the shortest cell edge -- 3.77 A for
that acetone cell -- which is far too short for either dispersion or the
real-space Ewald split. Summing over lattice shifts instead decouples the
cutoff from the cell size, at a cost that is irrelevant for a unit cell of a
few hundred atoms.

What is computed is the *intermolecular* energy per molecule, so bonded and
intramolecular nonbonded terms cancel exactly against an isolated molecule held
at the same geometry. That makes the lattice energy directly comparable to a
gas-phase reference without ever evaluating one, and it is why the sublimation
enthalpy below needs no separate gas calculation.

Sublimation enthalpy follows the standard rigid-molecule result

    dH_sub(T) = -E_latt - 2RT

whose ``-2RT`` is the difference between the gas-phase ``4RT`` (3/2 RT
translation + 3/2 RT rotation + RT for pV) and the ``6RT`` carried classically
by the six rigid-body lattice modes that replace them in the crystal. It
neglects the difference in intramolecular vibration between phases and all
quantum (zero-point) corrections, both of which are small for a rigid molecule
but neither of which is zero.

References: Allen & Tildesley, *Computer Simulation of Liquids*, 2nd ed., ch. 2
(tail corrections) and ch. 12 (Ewald); Gavezzotti, *Acc. Chem. Res.* 27, 309
(1994) for the ``-2RT`` convention.
"""

